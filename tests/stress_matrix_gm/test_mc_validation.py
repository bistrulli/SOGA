"""
test_mc_validation.py — 15 Monte Carlo validation tests for matrix-GM ops.

Each test runs a SOGA program and compares:
  - relative mean error: |E_mc - E_soga| / max(|E_soga|, 1e-8)  <  tol_mean
  - relative Frobenius error: ||Cov_mc - Cov_soga||_F / max(||Cov_soga||_F, 1e-8)  <  tol_frob

MC samples are generated by sample_MN from mc_forward.py.
SOGA computes E[X[i,j]] for all elements; MC estimates E[X] from N iid samples.
For covariance: MC estimates empirical covariance of vec(X) samples.

Tolerance derivation (from plan §MC Tolerance Derivation):
  N=1e5: tol_mean=2%  (3-sigma bound=0.95%, margin 2.1x)
  N=1e5: tol_frob=5%  (3-sigma bound=1.34%, margin 3.7x)
  16×16 N_mean=2e4: tol_mean=5% (3-sigma=2.12%, margin 2.4x)
  16×16 N_cov=5e4:  tol_frob=10% (3-sigma=1.90%, margin 5.3x)

Run:
    pytest tests/stress_matrix_gm/test_mc_validation.py -v
    pytest tests/stress_matrix_gm/test_mc_validation.py -k "prog_1_to_8" -v   -> 8
    pytest tests/stress_matrix_gm/test_mc_validation.py -k "prog_9_to_13" -v  -> 5
    pytest tests/stress_matrix_gm/test_mc_validation.py -k "prog_14_or_15" -v -> 2
"""

