def test_prog13_composite_chain():
    """Prog 13: chain: Y=A@X, Z=transp(Y), z00=Z[0,0]. E[z00] = (A@M)[0,0]^T."""
    # Y = A@X → E[Y] = A@M. Z = transp(Y) → E[Z] = (A@M)^T = E[Y]^T.
    # E[z00] = E[Y]^T[0,0] = E[Y][0,0] (transpose doesn't change diagonal for 2x2 if square)
    # Actually Z[0,0] = Y[0,0] for square transpose.
    A = np.array([[2.0, 0.0], [0.0, 1.0]])
    M = np.array([[1.0, 2.0], [3.0, 4.0]])
    E_Y = A @ M  # [[2,4],[3,4]]
