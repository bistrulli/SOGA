    assert rc == 0, f"rc={rc}\nstderr:{stderr[:300]}"
    # SOGA exact result
    assert abs(parse_e(stdout, "x00") - 3.0) < 1e-5, "E[x00] after write should be 3.0"
    # x11 is conditioned on X[0,0]=3: E[x11|X[0,0]=3] = E[X[1,1]] + Cov(x11,x00)/Var(x00)*(3-0)
    # For iso U=V=I: Cov(X[1,1], X[0,0]) = U[1,0]*V[1,0] = 0 (iso), so E[x11|...] = 0
    assert abs(parse_e(stdout, "x11") - 0.0) < 1e-5, "E[x11|X[0,0]=3] should be 0 for iso"


