def run_soga(program_text: str, timeout: int = 60) -> tuple:
    """Run a SOGA program via subprocess. Return (stdout, stderr, returncode)."""
    with tempfile.NamedTemporaryFile(mode="w", suffix=".soga", delete=False) as f:
        f.write(program_text)
        fname = f.name
    try:
        result = subprocess.run(
            [PYTHON, SOGA_PY, "-f", fname],
            capture_output=True, text=True, timeout=timeout,
            cwd=_SRC,
        )
        return result.stdout, result.stderr, result.returncode
    finally:
        os.unlink(fname)


def parse_e(output: str, var: str) -> float:
    """Parse E[var] from SOGA stdout."""
    m = re.search(rf"E\[{re.escape(var)}\]:\s+([-\d.eE+]+)", output)
    if m is None:
        raise AssertionError(f"E[{var}] not found in:\n{output[:600]}")
    return float(m.group(1))


def extract_soga_mean_matrix(stdout: str, var: str, m: int, n: int) -> np.ndarray:
    """Extract E[VAR] matrix from SOGA output by parsing E[var_ij] scalars."""
    M_soga = np.zeros((m, n))
    for i in range(m):
        for j in range(n):
            name = f"{var.lower()}{i}{j}"
            M_soga[i, j] = parse_e(stdout, name)
    return M_soga


def mc_check(
    M_soga: np.ndarray,
    M_mc: np.ndarray,
    tol_mean: float,
    label: str = "",
) -> None:
    """Assert relative mean error < tol_mean."""
    denom = max(float(np.max(np.abs(M_soga))), 1e-8)
    rel_err = float(np.max(np.abs(M_soga - M_mc))) / denom
    assert rel_err < tol_mean, (
        f"{label}: max rel mean error {rel_err:.3%} >= tol {tol_mean:.3%}\n"
        f"  SOGA: {np.round(M_soga, 4)}\n  MC: {np.round(M_mc, 4)}"
    )


def mc_check_cov(
    Cov_soga: np.ndarray,
    Cov_mc: np.ndarray,
    tol_frob: float,
    label: str = "",
) -> None:
    """Assert relative Frobenius covariance error < tol_frob."""
    denom = max(float(np.linalg.norm(Cov_soga, "fro")), 1e-8)
    rel_err = float(np.linalg.norm(Cov_soga - Cov_mc, "fro")) / denom
    assert rel_err < tol_frob, (
        f"{label}: Frob rel cov error {rel_err:.3%} >= tol {tol_frob:.3%}"
    )


def soga_kron_cov(U: np.ndarray, V: np.ndarray) -> np.ndarray:
    """Compute kron(V, U) — the true covariance of vec(X) in V⊗U convention."""
    return np.kron(V, U)


